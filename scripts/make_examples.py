"""Generate the two labeled SYNTHETIC example CVs and their metadata files.

Both examples come from the same synthetic thin-film electrode model
(benchcheck.synth.thinfilm) loosely inspired by a two-step insertion electrode
such as LiMn2O4 in aqueous LiCl. They differ only in the upper vertex:

* synthetic_lmo_clear_return: 0.30 -> 1.10 V, clear return peaks.
* synthetic_lmo_weak_return:  0.30 -> 1.25 V. Above ~1.15 V the model adds an
  irreversible anodic side current and a potential-dependent loss of the
  oxidized state, which weakens the return peaks. This is a deliberately
  exaggerated stress case so every feature is unambiguous.

Peak positions and currents are illustrative; they are not measured data and
are not fitted to any publication. Run: python scripts/make_examples.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from benchcheck.synth.thinfilm import Site, ThinFilmParams, simulate, write_csv  # noqa: E402

OUT = ROOT / "examples"

COMMON_METADATA = {
    "electrode_material": "LiMn2O4 composite (LMO / carbon black / PVDF)",
    "process_type": "electrode_material",
    "electrolyte": "1 M LiCl",
    "solvent": "aqueous",
    "reference_electrode": "ag_agcl_3m_kcl",
    "scan_rate": {"value": 1.0, "unit": "mV/s"},
    "active_mass_mg": 0.7,
    "electrode_area_cm2": None,
    "temperature_c": 25.0,
    "ph": None,
    "counter_electrode": "Pt wire",
    "ir_compensation": None,
}


def params(e_high: float) -> ThinFilmParams:
    return ThinFilmParams(
        sites=[Site(e0=0.80, charge_c=0.15, k0=0.02), Site(e0=0.95, charge_c=0.15, k0=0.02)],
        e_low=0.30,
        e_high=e_high,
        e_start=0.30,
        scan_rate=0.001,
        n_cycles=3,
        step_v=0.001,
        c_dl=0.04,
        tau_dl=2.0,
        i0_side=2.0e-4,
        e_side=1.20,
        b_side=0.05,
        k_loss0=2.0e-3,
        e_loss=1.20,
        b_loss=0.04,
        noise_a=4.0e-6,
        seed=7,
    )


def ground_truth(sim: dict, p: ThinFilmParams) -> dict:
    """Faradaic-only peak ratios and charge balance per cycle, from the model components."""
    E, far = sim["potential_v"], sim["components"]["faradaic"]
    n_half = int(round((p.e_high - p.e_low) / p.step_v))
    rows = []
    for c in range(p.n_cycles):
        a, mid, b = 2 * c * n_half, 2 * c * n_half + n_half, 2 * (c + 1) * n_half
        f_e, f_i, r_e, r_i = E[a:mid], far[a:mid], E[mid:b], far[mid:b]
        def peak(es, ys, lo, hi, sign):
            m = (es > lo) & (es < hi)
            return float(np.max(sign * ys[m]))
        a1, a2 = peak(f_e, f_i, 0.70, 0.90, 1), peak(f_e, f_i, 0.90, 1.05, 1)
        c1, c2 = peak(r_e, r_i, 0.65, 0.85, -1), peak(r_e, r_i, 0.85, 1.00, -1)
        rows.append({
            "cycle": c + 1,
            "faradaic_ratio_C1_A1": round(c1 / a1, 3),
            "faradaic_ratio_C2_A2": round(c2 / a2, 3),
            "faradaic_charge_ratio": round(float(-np.sum(r_i) / np.sum(f_i)), 3),
        })
    side_vertex = float(p.i0_side * np.exp((p.e_high - p.e_side) / p.b_side))
    return {
        "per_cycle": rows,
        "side_current_at_upper_vertex_mA": round(side_vertex * 1e3, 4),
        "electroactive_charge_lost_after_run_fraction": round(float(sim["lost_charge_c"][-1] / 0.30), 3),
    }


EXAMPLES = [
    {
        "id": "synthetic_lmo_clear_return",
        "title": "Synthetic CV · clear return peak",
        "e_high": 1.10,
        "summary": (
            "SYNTHETIC data. Two-step insertion-electrode model scanned 0.30 → 1.10 V vs Ag/AgCl at 1 mV/s for "
            "3 cycles. The return (cathodic) peaks mirror the forward (anodic) peaks."
        ),
    },
    {
        "id": "synthetic_lmo_weak_return",
        "title": "Synthetic CV · weak return peak",
        "e_high": 1.25,
        "summary": (
            "SYNTHETIC data. Same model scanned 0.30 → 1.25 V vs Ag/AgCl at 1 mV/s for 3 cycles. Above ~1.15 V the "
            "generator adds an irreversible anodic side current and a loss of the oxidized state, so the return peaks "
            "are weak and the peaks fade from cycle to cycle."
        ),
    },
]


def main() -> None:
    OUT.mkdir(exist_ok=True)
    for ex in EXAMPLES:
        p = params(ex["e_high"])
        sim = simulate(p)
        csv_name = f"{ex['id']}.csv"
        write_csv(
            OUT / csv_name,
            sim,
            [
                "SYNTHETIC DATA - generated by BenchCheck scripts/make_examples.py; not a measurement.",
                ex["summary"],
                "Columns: time/s, Ewe/V (vs Ag/AgCl 3 M KCl), <I>/mA (anodic positive).",
            ],
        )
        meta = {
            "id": ex["id"],
            "title": ex["title"],
            "synthetic": True,
            "summary": ex["summary"],
            "file": csv_name,
            "mapping": {"potential": "Ewe/V", "current": "<I>/mA", "time": "time/s"},
            "units": {"potential": "V", "current": "mA", "time": "s"},
            "current_convention": "iupac",
            "metadata": COMMON_METADATA,
            "intentionally_missing": ["electrode_area_cm2", "ph", "ir_compensation"],
            "generator": {
                "script": "scripts/make_examples.py",
                "model": "benchcheck.synth.thinfilm (two Butler–Volmer sites + double layer + side current + loss term)",
                "parameters": p.to_dict(),
            },
            "ground_truth": ground_truth(sim, p),
        }
        (OUT / f"{ex['id']}.meta.json").write_text(json.dumps(meta, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"wrote {csv_name} ({sim['potential_v'].size} points)")


if __name__ == "__main__":
    main()
